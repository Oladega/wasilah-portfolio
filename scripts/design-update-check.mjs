import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true });
const page = await browser.newPage();
await page.emulateMedia({ reducedMotion: 'reduce' });
const base = process.env.BASE_URL || 'http://localhost:3001';
const errors = []; page.on('pageerror', e => errors.push(e.message));
await page.addInitScript(() => { const OriginalAudio = window.Audio; window.Audio = class extends OriginalAudio { constructor(src) { super(src); window.__testAudio=this; } }; });
await mkdir('docs/screenshots/design-update', {recursive:true});
for (const width of [1440,1024,768,430,375]) {
 await page.setViewportSize({width,height:932}); await page.goto(base);
 await page.locator('main > picture img').evaluate(img => img.decode());
 assert.ok(await page.locator('main > picture img').evaluate(img => img.currentSrc.includes('floral-wallpaper')));
 assert.equal(await page.getByRole('navigation',{name:'Social links',includeHidden:true}).count(),0);
 await page.screenshot({path:`docs/screenshots/design-update/home-${width}.png`});
 const nav=page.getByRole('navigation',{name:'Portfolio',exact:true});
 await nav.getByRole('button',{name:width<810?'About Me':'About Wasilah',exact:true}).click();
 const about=page.getByRole('dialog',{name:'About Wasilah',exact:true}); await about.waitFor();
 assert.equal(await about.locator('img').count(),1);
 await about.locator('img').evaluateAll(images=>Promise.all(images.map(image=>{image.loading='eager';return image.decode();})));
 const box=await about.boundingBox();assert.ok(box.width>=width*.85);assert.ok(box.height>=750);
 const photos=about.locator('img').first().locator('../..');
 const proportions=await photos.evaluate(el=>({row:el.clientWidth/el.parentElement.clientWidth,imgs:[...el.querySelectorAll('img')].map(img=>({ratio:img.parentElement.clientWidth/el.parentElement.parentElement.clientWidth,fit:getComputedStyle(img).objectFit}))}));
 assert.ok(proportions.row<=(width<810?1.01:.81));
 assert.ok(proportions.imgs.every(img=>img.ratio<=(width<810?1.01:.36) && img.fit==='contain'));
 assert.equal(await about.locator('[id="about-capabilities"]').count(),1);
 assert.equal(await about.locator('dt').count(),5);
 await page.screenshot({path:`docs/screenshots/design-update/about-${width}.png`});
 await page.keyboard.press('Escape');
 await nav.getByRole('button',{name:width<810?'Contact me':'Contact Me',exact:true}).click();
 const contact=page.getByRole('dialog',{name:'Contact Me',exact:true});await contact.waitFor();
 assert.equal(await contact.getByRole('heading',{name:/Have something/}).count(),1);
 const links=contact.getByRole('navigation',{name:'Contact options'}).getByRole('link');
 assert.deepEqual(await links.evaluateAll(items=>items.map(item=>item.getAttribute('href'))),['https://www.linkedin.com/in/wasilat-atilade-2b54a823a/','mailto:wasilahatilade01@gmail.com','https://x.com/TheWasilah']);
 assert.equal(await contact.locator('iframe').count(),0);
 assert.equal(await contact.getByText('Résumé.pdf',{exact:true}).count(),0);
 await page.screenshot({path:`docs/screenshots/design-update/contact-${width}.png`});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.keyboard.press('Escape');
 await page.getByRole('button',{name:'Play background music',exact:true}).click();
 await page.getByRole('button',{name:'Mute background music',exact:true}).waitFor();
 await page.waitForTimeout(1000);
 const audio=await page.evaluate(()=>({src:window.__testAudio.currentSrc,time:window.__testAudio.currentTime,duration:window.__testAudio.duration,paused:window.__testAudio.paused}));
 assert.ok(audio.src.endsWith('jazzy-amapiano-bounce.m4a'));assert.ok(audio.time>0);assert.ok(audio.duration>49 && audio.duration<52);assert.equal(audio.paused,false);
 await page.getByRole('button',{name:'Mute background music',exact:true}).click();
}
assert.deepEqual(errors,[]);await browser.close();
console.log('Passed: Floral wallpaper, no dock, expanded About with one uncropped photo below 80% width, complete Contact links, actual amapiano playback and five responsive layouts.');
